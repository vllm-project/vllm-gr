def _run_child_slice(
    *,
    args: argparse.Namespace,
    mode: str,
    nominal_seq_len: int,
    run_seed: int,
) -> dict[str, Any]:
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        suffix=".json",
        delete=False,
    ) as temp_file:
        child_output_json = temp_file.name

    command = _build_child_command(
        args=args,
        mode=mode,
        nominal_seq_len=nominal_seq_len,
        run_seed=run_seed,
        child_output_json=child_output_json,
    )

    try:
        result = subprocess.run(
            command,
            check=False,
            text=True,
            capture_output=True,
        )
        if result.stdout:
            print(result.stdout, end="" if result.stdout.endswith("\n") else "\n")
        if result.stderr:
            print(result.stderr, end="" if result.stderr.endswith("\n") else "\n")
        if result.returncode != 0:
            failure = _format_child_failure(
                result=result,
                mode=mode,
                nominal_seq_len=nominal_seq_len,
            )
            return {
                "mode": mode,
                "device_type": None,
                "block_size": None,
                "dtype": _resolve_runtime_dtype(args) or "runtime-default",
                "success": False,
                "error": failure,
                "result": {
                    "nominal_seq_len": nominal_seq_len,
                    "status": "failed",
                    "error_message": failure["message"],
                    "error_returncode": failure["returncode"],
                    "error_signal": failure["signal"],
                },
            }

        with open(child_output_json, "r", encoding="utf-8") as f:
            child_report = json.load(f)
        child_report["success"] = True
        child_report["error"] = None
        return child_report
    finally:
        try:
            os.remove(child_output_json)
        except OSError:
            pass


def _run_single_slice(
    *,
    args: argparse.Namespace,
    mode: str,
    nominal_seq_len: int,
    template_case: dict[str, Any],
    run_seed: int,
) -> dict[str, Any]:
    llm = None
    try:
        llm = _build_llm(args=args, mode=mode)
        device_type = describe_runtime(expected_device=args.expect_device)
        if mode == "yuanrong" and device_type != "npu":
            raise RuntimeError(
                "Yuanrong benchmark mode requires NPU runtime. "
                f"Detected device_type={device_type!r}."
            )

        block_size = _get_runtime_cache_block_size(llm)
        print(f"device_type={device_type} block_size={block_size}")

        if args.scenario == "capacity":
            benchmark_slice = _build_capacity_benchmark_slice(
                llm=llm,
                template_case=template_case,
                nominal_seq_len=nominal_seq_len,
                warm_unique_requests=args.warm_unique_requests,
                probe_oldest_requests=args.probe_oldest_requests,
                revisit_rounds=args.revisit_rounds,
                run_seed=run_seed,
            )
        else:
            benchmark_slice = _build_benchmark_slice(
                llm=llm,
                template_case=template_case,
                nominal_seq_len=nominal_seq_len,
                target_hit_rate=args.target_hit_rate,
                measure_cases=args.measure_cases,
                run_seed=run_seed,
            )
        print(
            "\n  -- scenario={scenario} seq_len={nominal_seq_len} "
            "target_prompt_len={target_prompt_len} "
            "requested_hit_tokens={requested_prefix_hit_tokens} "
            "shared_prefix_tokens={shared_prefix_tokens} "
            "requested_hit_rate={requested_prefix_hit_rate:.4%} "
            "effective_hit_rate={expected_prefix_hit_rate:.4%}".format(**benchmark_slice)
        )
        if args.scenario == "capacity":
            measurement = _run_capacity_measurement_cases(
                llm=llm,
                benchmark_slice=benchmark_slice,
                show_case_limit=args.show_case_limit,
            )
        else:
            measurement = _run_measurement_cases(
                llm=llm,
                benchmark_slice=benchmark_slice,
                show_case_limit=args.show_case_limit,
            )
        return {
            "mode": mode,
            "device_type": device_type,
            "block_size": block_size,
            "dtype": _resolve_runtime_dtype(args) or "runtime-default",
            "result": {
                "scenario": benchmark_slice["scenario"],
                "nominal_seq_len": benchmark_slice["nominal_seq_len"],
                "target_prompt_len": benchmark_slice["target_prompt_len"],
                "history_len": benchmark_slice["history_len"],
                "context_len": benchmark_slice["context_len"],
                "candidate_len": benchmark_slice["candidate_len"],
                "shared_history_len": benchmark_slice.get("shared_history_len"),
                "requested_prefix_hit_tokens": benchmark_slice["requested_prefix_hit_tokens"],
                "shared_prefix_tokens": benchmark_slice["shared_prefix_tokens"],
                "requested_prefix_hit_rate": benchmark_slice["requested_prefix_hit_rate"],
                "max_cacheable_prefix_tokens": benchmark_slice["max_cacheable_prefix_tokens"],
                "expected_prefix_hit_rate": benchmark_slice["expected_prefix_hit_rate"],
                "warm_unique_requests": benchmark_slice.get("warm_unique_requests"),
                "probe_oldest_requests": benchmark_slice.get("probe_oldest_requests"),
                "revisit_rounds": benchmark_slice.get("revisit_rounds"),
                **measurement,
            },
        }
    finally:
        if llm is not None:
            llm.shutdown()
            llm = None
        gc.collect()
        release_accelerator_memory()


def main() -> int:
    args = _parse_args()
    sequence_lengths = _parse_sequence_lengths(args.sequence_lengths)
    payload = _load_json(args.input_json)
    template_case = _validate_input_payload(payload)[0]

    if args.child_run:
        resolved_modes = _resolve_modes(args.modes)
        if len(resolved_modes) != 1:
            raise RuntimeError("--child-run requires exactly one mode")
        if len(sequence_lengths) != 1:
            raise RuntimeError("--child-run requires exactly one sequence length")
        child_report = _run_single_slice(
            args=args,
            mode=resolved_modes[0],
            nominal_seq_len=sequence_lengths[0],
            template_case=template_case,
            run_seed=int(args.child_run_seed),
        )
        if not args.child_output_json:
            raise RuntimeError("--child-run requires --child-output-json")
        Path(args.child_output_json).write_text(
            json.dumps(child_report, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        return 0

    report: dict[str, Any] = {
        "model": args.model,
        "input_json": args.input_json,
        "scenario": args.scenario,
        "sequence_lengths": sequence_lengths,
        "measure_cases": int(args.measure_cases),
        "target_hit_rate": float(args.target_hit_rate),
        "gpu_memory_utilization": float(args.gpu_memory_utilization),
        "dtype": args.dtype,
        "modes": [],
    }

    print("=" * 72)
    print(" Prefix Cache Scaling Benchmark")
    print("=" * 72)
    print(f"model={args.model}")
    print(f"input_json={args.input_json}")
    print(f"scenario={args.scenario}")
    print(f"sequence_lengths={sequence_lengths}")
    print(f"measure_cases={args.measure_cases}")
    print(f"target_hit_rate={args.target_hit_rate:.2%}")
    print(f"gpu_memory_utilization={args.gpu_memory_utilization:.2f}")
    if args.scenario == "capacity":
        print(f"warm_unique_requests={args.warm_unique_requests}")
        print(f"probe_oldest_requests={args.probe_oldest_requests}")
        print(f"revisit_rounds={args.revisit_rounds}")
    print(f"dtype={args.dtype}")

    resolved_modes = _resolve_modes(args.modes)
    for mode_idx, mode in enumerate(resolved_modes):
        print(f"\n== Mode: {mode} ==")
        mode_report = {
            "mode": mode,
            "device_type": None,
            "block_size": None,
            "dtype": _resolve_runtime_dtype(args) or "runtime-default",
            "results": [],
        }

        for seq_idx, nominal_seq_len in enumerate(sequence_lengths):
            run_seed = (mode_idx + 1) * 1_000_000 + (seq_idx + 1) * 10_000
            child_report = _run_child_slice(
                args=args,
                mode=mode,
                nominal_seq_len=nominal_seq_len,
                run_seed=run_seed,
            )
            if not child_report.get("success", False):
                mode_report["results"].append(child_report["result"])
                print(
                    "  !! FAILED seq_len={seq_len} returncode={returncode} signal={signal_name}".format(
                        seq_len=nominal_seq_len,
                        returncode=child_report["error"]["returncode"],
                        signal_name=child_report["error"]["signal"] or "unknown",
                    )
                )
                if child_report["error"]["stderr_tail"]:
                    print("  stderr_tail:")
                    print(child_report["error"]["stderr_tail"])
                if child_report["error"]["stdout_tail"]:
                    print("  stdout_tail:")
                    print(child_report["error"]["stdout_tail"])
                if args.fail_fast:
                    raise RuntimeError(child_report["error"]["message"])
                continue

            if mode_report["device_type"] is None:
                mode_report["device_type"] = child_report["device_type"]
            if mode_report["block_size"] is None:
                mode_report["block_size"] = child_report["block_size"]
            mode_report["results"].append(child_report["result"])

        report["modes"].append(mode_report)

    print("\n== Summary ==")
    for mode_report in report["modes"]:
        print(
            f"mode={mode_report['mode']} "
            f"device_type={mode_report['device_type']} "
            f"dtype={mode_report['dtype']}"
        )
        for result in mode_report["results"]:
            if result.get("status") == "failed":
                print(
                    "  seq_len={nominal_seq_len} FAILED returncode={error_returncode} "
                    "signal={error_signal} reason={error_message}".format(**result)
                )
                continue
            if result.get("scenario") == "capacity":
                print(
                    "  seq_len={nominal_seq_len} prompt_len={target_prompt_len} "
                    "warm_unique_requests={warm_unique_requests} "
                    "probe_oldest_requests={probe_oldest_requests} "
                    "revisit_rounds={revisit_rounds} "
                    "effective_hit_rate={expected_prefix_hit_rate:.4%} "
                    "hbm_hit_rate={hbm_hit_rate:.4%} connector_hit_rate={connector_hit_rate:.4%} "
                    "cache_hit_rate={cache_hit_rate:.4%} "
                    "throughput_seq_s={throughput_seq_s:.4f}".format(**result)
                )
            else:
                print(
                    "  seq_len={nominal_seq_len} prompt_len={target_prompt_len} "
                    "requested_hit_rate={requested_prefix_hit_rate:.4%} "
                    "effective_hit_rate={expected_prefix_hit_rate:.4%} "
                    "hbm_hit_rate={hbm_hit_rate:.4%} connector_hit_rate={connector_hit_rate:.4%} "
                    "cache_hit_rate={cache_hit_rate:.4%} "
                    "throughput_seq_s={throughput_seq_s:.4f}".format(**result)
                )

    if args.output_json:
        output_path = Path(args.output_json)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(
            json.dumps(report, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        print(f"\nWrote report: {output_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
