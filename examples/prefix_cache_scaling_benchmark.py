def _build_capacity_benchmark_slice(
    *,
    llm,
    template_case: dict[str, Any],
    nominal_seq_len: int,
    warm_unique_requests: int,
    probe_oldest_requests: int,
    revisit_rounds: int,
    run_seed: int,
) -> dict[str, Any]:
    if warm_unique_requests <= 0:
        raise ValueError("--warm-unique-requests must be > 0")
    if probe_oldest_requests <= 0:
        raise ValueError("--probe-oldest-requests must be > 0")
    if revisit_rounds <= 0:
        raise ValueError("--revisit-rounds must be > 0")
    if probe_oldest_requests > warm_unique_requests:
        raise ValueError("--probe-oldest-requests must be <= --warm-unique-requests")

    block_size = _get_runtime_cache_block_size(llm)
    prompt_layout = _derive_prompt_layout(llm, template_case)
    target_prompt_len = nominal_seq_len
    history_len = target_prompt_len - prompt_layout["overhead"]
    if history_len <= 0:
        raise RuntimeError(f"Target prompt length {target_prompt_len} is too small for this schema")

    max_cacheable_prefix_tokens = _estimate_cacheable_prefix_tokens(
        target_prompt_len,
        block_size,
    )
    warm_cases: list[dict[str, Any]] = []
    for warm_idx in range(warm_unique_requests):
        warm_cases.append(
            _build_exact_revisit_case(
                template_case=template_case,
                history_len=history_len,
                variant_seed=run_seed + (warm_idx + 1) * (history_len + 7),
                case_id=f"warm_capacity_{nominal_seq_len}_{warm_idx + 1:03d}",
                user_id=f"warm_capacity_user_{nominal_seq_len}_{warm_idx + 1:03d}",
            )
        )

    probe_source_cases = warm_cases[:probe_oldest_requests]
    measurement_cases: list[dict[str, Any]] = []
    for round_idx in range(revisit_rounds):
        for probe_idx, source_case in enumerate(probe_source_cases, start=1):
            revisited_case = copy.deepcopy(source_case)
            revisited_case["case_id"] = (
                f"probe_capacity_{nominal_seq_len}_r{round_idx + 1:02d}_{probe_idx:03d}"
            )
            revisited_case["user_id"] = source_case["user_id"]
            measurement_cases.append(revisited_case)

    warm_prompt_len = _estimate_prompt_token_ids_len(llm, warm_cases[0])
    if warm_prompt_len != target_prompt_len:
        raise RuntimeError(
            "Synthetic capacity warm case prompt length mismatch: "
            f"expected={target_prompt_len} got={warm_prompt_len}"
        )

    probe_prompt_len = _estimate_prompt_token_ids_len(llm, measurement_cases[0])
    if probe_prompt_len != target_prompt_len:
        raise RuntimeError(
            "Synthetic capacity probe case prompt length mismatch: "
            f"expected={target_prompt_len} got={probe_prompt_len}"
        )

    effective_hit_rate = _hit_rate(
        max_cacheable_prefix_tokens,
        target_prompt_len,
    )
    return {
        "scenario": "capacity",
        "nominal_seq_len": nominal_seq_len,
        "target_prompt_len": target_prompt_len,
        "history_len": history_len,
        "context_len": prompt_layout["context_len"],
        "candidate_len": prompt_layout["candidate_len"],
        "requested_prefix_hit_tokens": max_cacheable_prefix_tokens,
        "shared_prefix_tokens": max_cacheable_prefix_tokens,
        "requested_prefix_hit_rate": 1.0,
        "expected_prefix_hit_rate": effective_hit_rate,
        "max_cacheable_prefix_tokens": max_cacheable_prefix_tokens,
        "warm_unique_requests": warm_unique_requests,
        "probe_oldest_requests": probe_oldest_requests,
        "revisit_rounds": revisit_rounds,
        "warm_cases": warm_cases,
        "measurement_cases": measurement_cases,
    }


def _run_measurement_cases(
    *,
    llm,
    benchmark_slice: dict[str, Any],
    show_case_limit: int,
) -> dict[str, Any]:
    warm_case = benchmark_slice["warm_case"]
    measurement_cases = benchmark_slice["measurement_cases"]

    before_warm = _snapshot_prefix_cache_counters(llm)
    warm_output = llm.recommend(prompts=[_prompt_from_case(warm_case)], use_tqdm=False)[0]
    if not getattr(warm_output, "finished", True):
        raise RuntimeError("Warm-up request did not finish successfully")
    after_warm = _snapshot_prefix_cache_counters(llm)
    warm_delta = _diff_counters(after_warm, before_warm)
    warm_hbm_hits = warm_delta["hits"]
    warm_connector_hits = warm_delta["connector_hits"]
    warm_queries = (
        warm_delta["connector_queries"]
        if warm_delta["connector_queries"] > 0
        else warm_delta["queries"]
    )

    before_all = _snapshot_prefix_cache_counters(llm)
    start_all = time.perf_counter()
    per_case_rows: list[dict[str, Any]] = []

    for index, case in enumerate(measurement_cases, start=1):
        before = _snapshot_prefix_cache_counters(llm)
        start = time.perf_counter()
        output = llm.recommend(prompts=[_prompt_from_case(case)], use_tqdm=False)[0]
        latency_ms = (time.perf_counter() - start) * 1000.0
        if not getattr(output, "finished", True):
            raise RuntimeError(f"Measurement request {case['case_id']} did not finish")
        after = _snapshot_prefix_cache_counters(llm)
        delta = _diff_counters(after, before)
        hbm_hits = delta["hits"]
        connector_hits = delta["connector_hits"]
        total_hits = hbm_hits + connector_hits
        queries = delta["connector_queries"] if delta["connector_queries"] > 0 else delta["queries"]
        per_case_rows.append(
            {
                "index": index,
                "case_id": case["case_id"],
                "latency_ms": latency_ms,
                "hbm_hit_rate": _hit_rate(hbm_hits, queries),
                "connector_hit_rate": _hit_rate(connector_hits, queries),
                "cache_hit_rate": _hit_rate(total_hits, queries),
            }
        )

    elapsed_s = time.perf_counter() - start_all
    after_all = _snapshot_prefix_cache_counters(llm)
    delta_all = _diff_counters(after_all, before_all)
    probe_hbm_hits = delta_all["hits"]
    probe_connector_hits = delta_all["connector_hits"]
    probe_queries = (
        delta_all["connector_queries"]
        if delta_all["connector_queries"] > 0
        else delta_all["queries"]
    )
    total_hbm_hits = warm_hbm_hits + probe_hbm_hits
    total_connector_hits = warm_connector_hits + probe_connector_hits
    total_hits = total_hbm_hits + total_connector_hits
    total_queries = warm_queries + probe_queries
    throughput_seq_s = float(len(measurement_cases)) / elapsed_s if elapsed_s > 0 else 0.0
    avg_latency_ms = (
        sum(row["latency_ms"] for row in per_case_rows) / len(per_case_rows)
        if per_case_rows
        else 0.0
    )

    print(
        "  reset_ok={reset_ok} warm_case={warm_case} "
        "measure_cases={measure_cases} elapsed_s={elapsed_s:.4f} "
        "throughput_seq_s={throughput_seq_s:.4f} "
        "hbm_hit_rate={hbm_hit_rate:.4%} connector_hit_rate={connector_hit_rate:.4%} "
        "cache_hit_rate={cache_hit_rate:.4%}".format(
            reset_ok="fresh_engine",
            warm_case=warm_case["case_id"],
            measure_cases=len(measurement_cases),
            elapsed_s=elapsed_s,
            throughput_seq_s=throughput_seq_s,
            hbm_hit_rate=_hit_rate(total_hbm_hits, total_queries),
            connector_hit_rate=_hit_rate(total_connector_hits, total_queries),
            cache_hit_rate=_hit_rate(total_hits, total_queries),
        )
    )
    print("  sample_cases:")
    for row in per_case_rows[: max(show_case_limit, 0)]:
        print(
            "    [{index:02d}] case_id={case_id} latency_ms={latency_ms:.3f} "
            "hbm={hbm_hit_rate:.4%} yuanrong={connector_hit_rate:.4%} "
            "total={cache_hit_rate:.4%}".format(**row)
        )
    if len(per_case_rows) > max(show_case_limit, 0):
        print(f"    ... ({len(per_case_rows) - max(show_case_limit, 0)} more cases)")

    return {
        "reset_ok": True,
        "warm_case_id": warm_case["case_id"],
        "measure_cases": len(measurement_cases),
        "elapsed_s": elapsed_s,
        "throughput_seq_s": throughput_seq_s,
        "avg_latency_ms": avg_latency_ms,
        "hbm_hit_rate": _hit_rate(total_hbm_hits, total_queries),
        "connector_hit_rate": _hit_rate(total_connector_hits, total_queries),
        "cache_hit_rate": _hit_rate(total_hits, total_queries),
        "cases": per_case_rows,
    }


