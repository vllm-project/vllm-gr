def _resolve_modes(raw_mode: str) -> list[str]:
    if raw_mode == "both":
        return ["local", "yuanrong"]
    return [raw_mode]


def _tail_text(value: str, *, max_lines: int = 40) -> str:
    if not value:
        return ""
    lines = value.splitlines()
    if len(lines) <= max_lines:
        return "\n".join(lines)
    return "\n".join(lines[-max_lines:])


def _format_child_failure(
    *,
    result: subprocess.CompletedProcess[str],
    mode: str,
    nominal_seq_len: int,
) -> dict[str, Any]:
    returncode = int(result.returncode)
    signal_name = None
    if returncode < 0:
        signal_value = -returncode
        try:
            signal_name = signal.Signals(signal_value).name
        except ValueError:
            signal_name = f"SIG{signal_value}"

    stdout_tail = _tail_text(result.stdout)
    stderr_tail = _tail_text(result.stderr)

    message = (
        f"Child benchmark slice failed: mode={mode} seq_len={nominal_seq_len} "
        f"returncode={returncode}"
    )
    if signal_name is not None:
        message += f" signal={signal_name}"

    return {
        "message": message,
        "returncode": returncode,
        "signal": signal_name,
        "stdout_tail": stdout_tail,
        "stderr_tail": stderr_tail,
    }


