def _hit_rate(hits: int, queries: int) -> float:
    if queries <= 0:
        return 0.0
    return float(hits) / float(queries)


def _get_runtime_cache_block_size(llm) -> int:
    engine = llm.get_engine()
    cache_config = getattr(engine.vllm_config, "cache_config", None)
    if cache_config is None:
        return 0
    return int(getattr(cache_config, "block_size", 0) or 0)


def _get_runtime_device_type(llm) -> str:
    engine = llm.get_engine()
    device_config = getattr(engine.vllm_config, "device_config", None)
    return str(getattr(device_config, "device_type", "unknown"))


def _estimate_cacheable_prefix_tokens(prompt_len: int, block_size: int) -> int:
    if prompt_len <= 1 or block_size <= 0:
        return 0
    return ((prompt_len - 1) // block_size) * block_size


def _align_hit_tokens_to_runtime_blocks(
    *,
    requested_hit_tokens: int,
    max_cacheable_prefix_tokens: int,
    block_size: int,
) -> int:
    if requested_hit_tokens <= 0 or max_cacheable_prefix_tokens <= 0:
        return 0
    if block_size <= 0:
        return min(requested_hit_tokens, max_cacheable_prefix_tokens)

    lower = min(
        (requested_hit_tokens // block_size) * block_size,
        max_cacheable_prefix_tokens,
    )
    upper = min(
        ((requested_hit_tokens + block_size - 1) // block_size) * block_size,
        max_cacheable_prefix_tokens,
    )

    candidates = sorted({lower, upper})
    if not candidates:
        return 0

    best = min(
        candidates,
        key=lambda candidate: (abs(candidate - requested_hit_tokens), candidate),
    )

    if best == 0 and max_cacheable_prefix_tokens >= block_size:
        return block_size
    return best


