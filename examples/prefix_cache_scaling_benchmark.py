def _parse_sequence_lengths(raw_value: str) -> list[int]:
    sequence_lengths: list[int] = []
    for part in raw_value.split(","):
        value = part.strip()
        if not value:
            continue
        sequence_lengths.append(int(value))
    if not sequence_lengths:
        raise ValueError("--sequence-lengths must contain at least one integer")
    if any(value <= 0 for value in sequence_lengths):
        raise ValueError("--sequence-lengths values must be > 0")
    return sequence_lengths


def _load_json(path: str) -> dict[str, Any]:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _validate_input_payload(payload: dict[str, Any]) -> list[dict[str, Any]]:
    meta = payload.get("meta", {})
    dataset = meta.get("dataset")
    if dataset is not None and dataset != DATASET_NAME:
        raise ValueError(f"Unsupported dataset: {dataset}, expected {DATASET_NAME}")

    cases = payload.get("cases")
    if not isinstance(cases, list) or not cases:
        raise ValueError("input JSON must contain a non-empty list field: cases")

    for case in cases:
        case_id = case.get("case_id")
        if not isinstance(case_id, str) or not case_id:
            raise ValueError("Every case must contain non-empty string case_id")
        if not isinstance(case.get("user_history"), list) or not case["user_history"]:
            raise ValueError(f"case={case_id} missing non-empty user_history list")
        if not isinstance(case.get("candidates"), list) or not case["candidates"]:
            raise ValueError(f"case={case_id} missing non-empty candidates list")
        if not isinstance(case.get("context"), dict):
            raise ValueError(f"case={case_id} missing context dict")
    return cases


def _prompt_from_case(case: dict[str, Any]) -> dict[str, Any]:
    return {
        "user_id": case["user_id"],
        "user_history": case["user_history"],
        "candidates": case["candidates"],
        "context": case["context"],
        "num_recommendations": len(case["candidates"]),
    }


def _estimate_prompt_token_ids_len(llm, case: dict[str, Any]) -> int:
    from vllm.pooling_params import PoolingParams

    engine = llm.get_engine()
    request = engine.input_processor.process_inputs(
        request_id=f"scaling-len-{case['case_id']}",
        prompt=_prompt_from_case(case),
        params=PoolingParams(task="embed"),
    )
    prompt_token_ids = getattr(request, "prompt_token_ids", None) or []
    return len(prompt_token_ids)


