"""Prefix-cache benchmark with scaling and cache-pressure scenarios.

This benchmark compares two runtime modes:

- local prefix cache only
- prefix cache with Yuanrong KV transfer enabled

Supported scenarios:

- scaling:
  For each requested sequence length, construct one warm-up request and a
  configurable number of measurement requests whose reusable prefix ratio is
  fixed to a target hit rate.

- capacity:
  Construct many unique long-prefix warm requests to put pressure on local KV
  cache capacity, then exactly revisit the oldest requests. This is intended
  to surface Yuanrong's larger remote cache capacity when local cache blocks
  are no longer sufficient.

The benchmark reports:

- measured prefix hit rate
- end-to-end throughput (seq/s)

Usage Examples
==============

1. Scaling scenario (default), both local and Yuanrong modes:

    python examples/prefix_cache_scaling_benchmark.py \\
        --model /workspace/ckpt/movielens_1m/800_truncated_new/converted \\
        --input-json ./examples/prefix_cache_benchmark.sample_input.json \\
        --expect-device npu \\
        --modes both \\
        --scenario scaling \\
        --sequence-lengths 1024,2048,4096

2. Capacity scenario with low GPU memory utilization to pressure local cache:

    python examples/prefix_cache_scaling_benchmark.py \\
        --model /workspace/ckpt/movielens_1m/800_truncated_new/converted \\
        --input-json ./examples/prefix_cache_benchmark.sample_input.json \\
        --expect-device npu \\
        --modes both \\
        --scenario capacity \\
        --sequence-lengths 1024 \\
        --gpu-memory-utilization 0.08 \\
        --warm-unique-requests 512 \\
        --probe-oldest-requests 128 \\
        --revisit-rounds 4

3. Local mode only (no Yuanrong connector):

    python examples/prefix_cache_scaling_benchmark.py \\
        --model /workspace/ckpt/movielens_1m/800_truncated_new/converted \\
        --input-json ./examples/prefix_cache_benchmark.sample_input.json \\
        --expect-device npu \\
        --modes local \\
        --scenario capacity \\
        --sequence-lengths 4096 \\
        --gpu-memory-utilization 0.1 \\
        --warm-unique-requests 300 \\
        --probe-oldest-requests 100

4. Yuanrong mode only with custom backend settings:

    python examples/prefix_cache_scaling_benchmark.py \\
        --model /workspace/ckpt/movielens_1m/800_truncated_new/converted \\
        --input-json ./examples/prefix_cache_benchmark.sample_input.json \\
        --expect-device npu \\
        --modes yuanrong \\
        --scenario capacity \\
        --sequence-lengths 4096 \\
        --gpu-memory-utilization 0.1 \\
        --warm-unique-requests 300 \\
        --probe-oldest-requests 100 \\
        --revisit-rounds 7 \\
        --backend yuanrong \\
        --kv-role kv_both

5. With JSON report output:

    python examples/prefix_cache_scaling_benchmark.py \\
        --model /workspace/ckpt/movielens_1m/800_truncated_new/converted \\
        --input-json ./examples/prefix_cache_benchmark.sample_input.json \\
        --expect-device npu \\
        --modes both \\
        --scenario capacity \\
        --sequence-lengths 1024 \\
        --gpu-memory-utilization 0.08 \\
        --output-json /tmp/benchmark_report.json

Arguments
---------

Model & Input:
  --model (required)
      Path to the converted HSTU model directory containing config.json.
  --input-json (default: examples/prefix_cache_benchmark.sample_input.json)
      Template input JSON path used to derive synthetic benchmark cases.
      For capacity scenario with large warm-unique-requests, use the
      high-diversity file generated by generate_capacity_benchmark_input.py.
  --expect-device (default: auto)
      Target device: "npu" for Ascend NPU, "cuda" for NVIDIA GPU.
  --dtype (default: auto)
      Runtime dtype override: auto, bfloat16, float16, float32.

Scenario & Sequence:
  --scenario (default: scaling)
      "scaling" — fixed hit ratio as prompt length scales.
      "capacity" — pressure local cache, then revisit old prefixes.
  --sequence-lengths (default: "1024,2048,4096,8192")
      Comma-separated nominal reusable-prefix lengths in tokens.
  --target-hit-rate (default: 0.5)
      Target reusable-prefix ratio over cacheable tokens (scaling scenario).
      Should align with whole KV blocks for block-based cache reuse.

Capacity Scenario Parameters:
  --warm-unique-requests (default: 64)
      Number of unique warm requests per sequence length. These fill the
      local KV cache to capacity before probing.
  --probe-oldest-requests (default: 16)
      Number of oldest warm requests to exactly revisit. These should have
      been evicted from local cache but may still exist in Yuanrong.
  --revisit-rounds (default: 1)
      How many rounds to repeat the exact-revisit probe set.

Scaling Scenario Parameters:
  --measure-cases (default: 20)
      Number of measurement requests per sequence length.

GRLLM Parameters:
  --max-uih-len / --max-seq-len (default: largest sequence length)
      GRLLM max_seq_len override.
  --max-candidates (default: 256)
      GRLLM max_candidates.
  --gpu-memory-utilization (default: 0.9)
      Fraction of GPU HBM for the vLLM engine. Lower values reduce local
      KV cache budget and make Yuanrong capacity advantages more visible.

Yuanrong / Connector Parameters:
  --modes (default: both)
      "local" — local prefix cache only.
      "yuanrong" — prefix cache with Yuanrong KV transfer.
      "both" — run both modes and compare.
  --backend (default: yuanrong)
      KV pool backend name for AscendStoreConnector.
  --kv-role (default: kv_both)
      KV role: kv_producer, kv_both, kv_consumer.
  --lookup-rpc-port (default: "1")
      Lookup RPC port for AscendStoreConnector.

Output & Control:
  --output-json (default: None)
      Optional JSON report output path.
  --show-case-limit (default: 3)
      Max number of sample rows shown per benchmark slice.
  --fail-fast (default: False)
      Stop the whole benchmark on the first failed slice.

Tips
----

- For reproducible results, set PYTHONHASHSEED before running:
      export PYTHONHASHSEED=0
  This ensures consistent block hash generation across runs.

- For capacity scenario, use the high-diversity input file to avoid
  artificial prefix overlap in warm requests:
      python examples/generate_capacity_benchmark_input.py
      Then pass --input-json ./examples/prefix_cache_benchmark.capacity_input.json

- Lower --gpu-memory-utilization (e.g., 0.08-0.1) to create more cache
  pressure and make Yuanrong's remote cache advantage visible.

- The benchmark spawns a child process per (mode, sequence-length) slice
  to ensure clean KV cache state. Use --fail-fast to stop on first error.
"""

